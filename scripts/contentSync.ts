// Pure helpers for `npm run content:sync` (plan.md §1.3). Kept separate from the CLI so they can
// be unit-tested without touching the file system.
import type { ContentItem, PromptSnapshot } from '../src/types/game'

export interface ContentRow {
  id: string
  mode: ContentItem['type']
  /** Exactly the PromptSnapshot that start_round copies into rounds.prompt_snapshot. */
  publicPayload: PromptSnapshot
  /** Only the fields reveal_round needs. Never sent to clients before the reveal. */
  answerKey: Record<string, unknown>
}

/** Splits a content item into what players may see and what only the server may see. */
export function splitContentItem(item: ContentItem): ContentRow {
  switch (item.type) {
    case 'trivia':
      return {
        id: item.id,
        mode: item.type,
        publicPayload: withoutUndefined({
          mode: 'trivia',
          prompt: item.prompt,
          choices: item.choices.map(({ id, label }) => ({ id, label })),
          category: item.category,
          difficulty: item.difficulty,
        }),
        answerKey: { correctChoiceId: item.correctChoiceId },
      }
    case 'word-guessing':
      return {
        id: item.id,
        mode: item.type,
        publicPayload: withoutUndefined({
          mode: 'word-guessing',
          prompt: item.prompt,
          category: item.category,
        }),
        answerKey: {
          targetAnswer: item.targetAnswer,
          acceptedAnswers: item.acceptedAnswers ?? [],
        },
      }
    case 'social':
      return {
        id: item.id,
        mode: item.type,
        publicPayload: withoutUndefined({
          mode: 'social',
          prompt: item.prompt,
          responseType: item.responseType,
          instructions: item.instructions,
          allowSelfVote: item.allowSelfVote ?? false,
        }),
        // Votes are scored by counting; there is no hidden answer.
        answerKey: {},
      }
  }
}

function withoutUndefined<T extends object>(value: T): T {
  return Object.fromEntries(Object.entries(value).filter(([, v]) => v !== undefined)) as T
}

/** A SQL string literal. JSON from JSON.stringify never contains a NUL, so doubling quotes is enough. */
function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

/**
 * The body of a content-sync migration: upserts every item and deactivates items that were
 * removed from the source. Deterministic (no timestamps), so unchanged content produces
 * identical SQL and the CLI can skip writing a migration.
 */
export function buildContentSyncSql(items: readonly ContentItem[]): string {
  const ids = new Set<string>()
  for (const item of items) {
    if (ids.has(item.id)) throw new Error(`Duplicate content id: ${item.id}`)
    ids.add(item.id)
  }
  if (items.length === 0) throw new Error('No content items found.')

  const rows = [...items]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(splitContentItem)
    .map(
      (row) =>
        `  (${literal(row.id)}, ${literal(row.mode)}, ${literal(JSON.stringify(row.publicPayload))}::jsonb, ${literal(JSON.stringify(row.answerKey))}::jsonb, true)`,
    )

  return [
    '-- Generated by `npm run content:sync` from src/content/. Do not edit by hand.',
    '-- Never edit this file once applied; run content:sync again to make a new one.',
    '',
    'insert into public.content_items (id, mode, public_payload, answer_key, active)',
    'values',
    rows.join(',\n'),
    'on conflict (id) do update set',
    '  mode = excluded.mode,',
    '  public_payload = excluded.public_payload,',
    '  answer_key = excluded.answer_key,',
    '  active = true;',
    '',
    '-- Items removed from src/content/ stay in the table (old rounds reference them) but are',
    '-- never picked again.',
    'update public.content_items',
    'set active = false',
    `where id not in (${[...ids].sort().map(literal).join(', ')});`,
    '',
  ].join('\n')
}

/** UTC timestamp in the Supabase CLI's migration format, e.g. 20261013140502. */
export function migrationTimestamp(date: Date): string {
  return date.toISOString().replace(/\D/g, '').slice(0, 14)
}
